// Writes out/sw.js after `next build`: a service worker that keeps the web
// app usable with no connection. Every page and script of this build is
// saved on install, so the app opens offline; data is already kept on the
// device by the sync layer. The Android app loads its files locally and never
// registers it.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const out = new URL("../out/", import.meta.url).pathname;

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(out).map((path) => "/" + relative(out, path).split(sep).join("/"));

const precache = new Set(["/"]);
for (const file of files) {
  if (file === "/sw.js" || file.startsWith("/backgrounds/")) continue;
  if (file.endsWith(".html")) {
    // Firebase Hosting serves clean URLs: /notes, not /notes.html.
    if (file === "/index.html" || file === "/404.html" || file.startsWith("/_not-found")) continue;
    precache.add(file.slice(0, -".html".length));
  } else if (file.endsWith(".txt") || file.startsWith("/_next/static/") || file.startsWith("/icons/")) {
    precache.add(file);
  } else if (file === "/manifest.webmanifest" || file === "/icon.svg") {
    precache.add(file);
  }
}

const hash = createHash("sha256");
for (const file of [...precache].sort()) {
  const path = file === "/" ? "index.html" : file.includes(".") || file.startsWith("/_next/") ? file.slice(1) : `${file.slice(1)}.html`;
  hash.update(file);
  hash.update(readFileSync(join(out, path)));
}
const version = hash.digest("hex").slice(0, 12);

const worker = `// Generated by scripts/build-sw.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const APP = "app-" + VERSION;
const MEDIA = "media-v1";
const PRECACHE = ${JSON.stringify([...precache].sort())};

// When each version's files were saved, so the newest can be told apart.
const SAVED_AT = "/__sw-saved-at";

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(APP)
      .then((cache) => cache.addAll(PRECACHE).then(() => cache.put(SAVED_AT, new Response(String(Date.now())))))
      .then(() => self.skipWaiting()),
  );
});

// The previous version's files are kept too: a tab still running it loads
// its pages' scripts on demand, and they must still be there.
self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const apps = await Promise.all(
        (await caches.keys())
          .filter((k) => k !== MEDIA)
          .map(async (k) => {
            const hit = await (await caches.open(k)).match(SAVED_AT);
            return { k, at: hit ? Number(await hit.text()) : 0 };
          }),
      );
      const keep = new Set([APP, ...apps.filter((a) => a.k !== APP).sort((a, b) => b.at - a.at).slice(0, 1).map((a) => a.k)]);
      await Promise.all(apps.filter((a) => !keep.has(a.k)).map((a) => caches.delete(a.k)));
      await self.clients.claim();
    })(),
  );
});

// Pages come from the network when it answers quickly, so a new version shows
// as soon as it is deployed; otherwise from this device.
async function page(request) {
  const cache = await caches.open(APP);
  try {
    const response = await Promise.race([
      fetch(request),
      new Promise((_, reject) => setTimeout(() => reject(new Error("slow")), 4000)),
    ]);
    if (response.ok) return response;
    throw new Error(String(response.status));
  } catch {
    const url = new URL(request.url);
    return (
      (await cache.match(url.pathname)) ??
      (await cache.match(url.pathname.replace(/\\/$/, ""))) ??
      (await cache.match("/")) ??
      Response.error()
    );
  }
}

async function cached(request, cacheName, store) {
  const cache = await caches.open(cacheName);
  // (Any saved version: an older tab asks for its own build's files.)
  const hit = (await cache.match(request, { ignoreSearch: true })) ?? (await caches.match(request, { ignoreSearch: true }));
  if (hit) return hit;
  const response = await fetch(request);
  if (store && response.ok) void cache.put(request, response.clone());
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith("/__/")) return;
  if (request.mode === "navigate") {
    event.respondWith(page(request));
  } else if (url.pathname.startsWith("/_next/static/") || url.pathname.startsWith("/icons/")) {
    event.respondWith(cached(request, APP, true));
  } else if (url.pathname.startsWith("/backgrounds/")) {
    // Liquid Glass backgrounds: saved the first time each is shown.
    event.respondWith(cached(request, MEDIA, true));
  } else if (url.pathname.endsWith(".txt")) {
    // Page data for in-app navigation: fresh when online, saved otherwise.
    event.respondWith(
      fetch(request).catch(async () => (await (await caches.open(APP)).match(url.pathname)) ?? Response.error()),
    );
  }
});
`;

writeFileSync(join(out, "sw.js"), worker);
console.log(`sw.js: ${precache.size} files, version ${version}`);
